@register.simple_tag
def badge(text, tone=None):
    key = str(text).lower()
    tone = tone or STATUS_TONE.get(key, "neutral")
    return format_html('<span class="inline-flex items-center rounded-full px-2 py-0.5 text-xs font-medium ring-1 ring-inset {}">{}</span>',
                       BADGES.get(tone, BADGES["neutral"]), text)


@register.simple_tag
def status_badge(obj_or_value, display=None):
    value = str(obj_or_value)
    return badge(display or value.replace("_", " ").title(), STATUS_TONE.get(value.lower(), "neutral"))


