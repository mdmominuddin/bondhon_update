from decimal import Decimal, InvalidOperation

from django import template
from django.utils.html import format_html

register = template.Library()


def _group_bd(int_part):
    """12345678 -> 1,23,45,678 (lakh / crore grouping used in Bangladesh)."""
    if len(int_part) <= 3:
        return int_part
    head, tail = int_part[:-3], int_part[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return ",".join(groups) + "," + tail


@register.filter
def bdnum(value, places=2):
    """Number with Bangladeshi digit grouping."""
    try:
        d = Decimal(str(value if value not in (None, "") else 0))
    except InvalidOperation:
        return value
    places = int(places)
    sign = "-" if d < 0 else ""
    q = f"{abs(d):.{places}f}"
    whole, _, frac = q.partition(".")
    out = _group_bd(whole)
    return f"{sign}{out}.{frac}" if frac else f"{sign}{out}"


@register.filter
def taka(value, places=2):
    return f"৳{bdnum(value, places)}"


@register.filter
def taka0(value):
    return f"৳{bdnum(value, 0)}"


@register.simple_tag(takes_context=True)
def url_replace(context, **kwargs):
    """Current query string with some parameters replaced (for pagination / filters)."""
    query = context["request"].GET.copy()
    for k, v in kwargs.items():
        query[k] = v
    return query.urlencode()


@register.filter
def get_item(d, key):
    try:
        return d.get(key)
    except AttributeError:
        return None


@register.filter
def initials(name):
    parts = [p for p in str(name).split() if p]
    return (parts[0][0] + (parts[-1][0] if len(parts) > 1 else "")).upper() if parts else "?"


@register.filter
def pct(value):
    try:
        return f"{min(max(float(value), 0), 100):.0f}"
    except (TypeError, ValueError):
        return "0"


